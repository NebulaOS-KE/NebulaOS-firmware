#!/bin/sh
# G50 (2026-10-17): the image's Python ABI fingerprint - the ONE place it is
# derived (architecture review 2026-10-17). nebulaos-post-build.sh writes it to
# /usr/share/nebulaos/python-abi and builds /etc/pip.conf from it; the SDK
# export copies that file; the NebulaOS package index serves wheels under
# <index>/<id>/ and checks every wheel against it.
#
# A wheel tag (cp312-cp312-linux_mips) says nothing about endianness, FP mode,
# NaN encoding, glibc or the libraries a .so links, so the fingerprint does:
#
#   python, soabi, platform_tag   from the target's _sysconfigdata
#   glibc                         from the target libc's own banner
#   gcc, arch, abi, fp32_mode,    from the build's .config
#   nan, endian
#   linkable                      the image's sonames a wheel may link
#                                 (LINKABLE below, those present)
#   id                            sha256 over all of the above, 16 hex
#
# Sourced. python_abi_fingerprint BR2_CONFIG TARGET_DIR STAGING_DIR prints the
# file (the target holds the sysconfig only as .pyc; staging has the .py).

# Libraries a published wheel may link against besides glibc itself. Adding
# one here changes the id (a new index path) - deliberately.
PYTHON_ABI_LINKABLE="libz.so.1 libpng16.so.16 libfreetype.so.6 libffi.so.8 libssl.so.3 libcrypto.so.3 libsodium.so.26 libstdc++.so.6 libgcc_s.so.1"
PYTHON_ABI_SCHEME=1

_pa_cfg() { # KEY - value of KEY in the .config, quotes removed
	sed -n "s/^$1=\"\{0,1\}\([^\"]*\)\"\{0,1\}$/\1/p" "$_pa_config" | head -1
}

_pa_sysconfig() { # KEY - from the target's _sysconfigdata
	sed -n "s/^ *'$1': '\([^']*\)',\{0,1\}$/\1/p" "$_pa_sysconfigdata" | head -1
}

python_abi_fingerprint() {
	_pa_config="$1"; _pa_target="$2"; _pa_staging="${3:-$2}"
	[ -f "$_pa_config" ] || { echo "python-abi: no .config at $_pa_config" >&2; return 1; }
	_pa_sysconfigdata=$(ls "$_pa_staging"/usr/lib/python3.*/_sysconfigdata__linux_*.py 2>/dev/null | head -1)
	[ -f "$_pa_sysconfigdata" ] || { echo "python-abi: no target _sysconfigdata" >&2; return 1; }

	_pa_python=$(_pa_sysconfig VERSION)
	_pa_soabi=$(_pa_sysconfig SOABI)
	_pa_arch=$(_pa_cfg BR2_ARCH)
	case "$_pa_arch" in
		# pip takes the platform from uname -m, which is "mips" on this
		# kernel for either endianness (ke-dev: "mips GNU/Linux").
		mips|mipsel) _pa_platform=linux_mips ;;
		*) echo "python-abi: platform tag for BR2_ARCH=$_pa_arch not known" >&2; return 1 ;;
	esac
	_pa_libc=$(ls "$_pa_target"/lib/libc.so.6 2>/dev/null | head -1)
	_pa_glibc=$(grep -ao 'GNU C Library [^)]*) [a-z ]*version [0-9.]*' "$_pa_libc" 2>/dev/null \
		| sed -n 's/.*version \([0-9][0-9.]*[0-9]\).*/\1/p' | head -1)
	[ -n "$_pa_python" ] && [ -n "$_pa_soabi" ] && [ -n "$_pa_glibc" ] || {
		echo "python-abi: python='$_pa_python' soabi='$_pa_soabi' glibc='$_pa_glibc' - incomplete" >&2
		return 1
	}
	_pa_endian=little
	grep -q '^BR2_ENDIAN="BIG"' "$_pa_config" && _pa_endian=big
	_pa_linkable=""
	for _pa_so in $PYTHON_ABI_LINKABLE; do
		if [ -e "$_pa_target/usr/lib/$_pa_so" ] || [ -e "$_pa_target/lib/$_pa_so" ]; then
			_pa_linkable="$_pa_linkable $_pa_so"
		fi
	done
	_pa_body=$(cat <<EOF
scheme=$PYTHON_ABI_SCHEME
python=$_pa_python
soabi=$_pa_soabi
platform_tag=$_pa_platform
glibc=$_pa_glibc
gcc=$(_pa_cfg BR2_GCC_VERSION)
arch=$(_pa_cfg BR2_GCC_TARGET_ARCH)
abi=$(_pa_cfg BR2_GCC_TARGET_ABI)
fp32_mode=$(_pa_cfg BR2_GCC_TARGET_FP32_MODE)
nan=$(_pa_cfg BR2_GCC_TARGET_NAN)
endian=$_pa_endian
linkable=${_pa_linkable# }
EOF
)
	printf '%s\n' "$_pa_body"
	printf 'id=%s\n' "$(printf '%s\n' "$_pa_body" | sha256sum | cut -c1-16)"
}

# pip.conf for an image with that fingerprint: only the NebulaOS index, only
# ready-made packages - pip on the printer never builds from source.
python_abi_pip_conf() { # INDEX_URL ABI_ID
	cat <<EOF
# NebulaOS (G50): app updates (Moonraker/Klipper requirements) install only
# ready-made packages for this image's Python ABI from the NebulaOS package
# index - never from PyPI, never built on the printer. Generated by the build.
[global]
index-url = ${1%/}/$2/
only-binary = :all:
disable-pip-version-check = true
EOF
}

# shellcheck shell=sh
#
# NebulaOS persistent hostname / IPv4 configuration - boot-time side
# (GUI/service readiness mission, 2026-10-09). Sourced by S01wifi and by
# /usr/libexec/nebulaos/nebulaos-osconfig's live-apply path (through
# `nebulaos-osconfig-netapply`), so the stanza a boot produces and the stanza
# a live change produces come from one function.
#
# Source of truth is /usr/data/nebulaos/network/osconfig.json, owned by
# nebulaos-osconfig (Python, validated, atomic). This file never parses JSON:
# the helper renders boot.env next to it - scalars only - and this library
# re-validates every value with case patterns. ANY doubt means DHCP with the
# default hostname, which is exactly the pre-mission behaviour plus the DHCP
# hostname option. A broken or hostile boot.env can therefore never stop the
# printer from getting an address.
#
#   NNET_HOSTNAME=<rfc1123 label>
#   NNET_MODE=dhcp|static
#   NNET_ADDRESS=a.b.c.d  NNET_NETMASK=a.b.c.d  NNET_GATEWAY=a.b.c.d
#   NNET_DNS="a.b.c.d a.b.c.d"
#
# /etc/network/interfaces (read-only rootfs, DHCP) is left untouched and stays
# the fallback: S01wifi only uses the generated file when it was written.

NNET_ENV="${NNET_ENV:-/usr/data/nebulaos/network/boot.env}"
NNET_RUN_DIR="${NNET_RUN_DIR:-/run/nebulaos/network}"
NNET_IFACES="${NNET_IFACES:-$NNET_RUN_DIR/interfaces}"
NNET_STATE="${NNET_STATE:-$NNET_RUN_DIR/boot-state}"
NNET_RESOLV="${NNET_RESOLV:-/tmp/resolv.conf}"
NNET_DEFAULT_HOSTNAME="${NNET_DEFAULT_HOSTNAME:-nebulaos}"
NNET_HOSTNAME_CMD="${NNET_HOSTNAME_CMD:-hostname}"
NNET_IFACE="${NNET_IFACE:-wlan0}"
# /etc/hosts is on the read-only rootfs (it names "buildroot"): a generated copy
# is bind-mounted over it at boot and rewritten in place on a hostname change.
NNET_HOSTS="${NNET_HOSTS:-$NNET_RUN_DIR/hosts}"
NNET_ETC_HOSTS="${NNET_ETC_HOSTS:-/etc/hosts}"
NNET_MOUNTS="${NNET_MOUNTS:-/proc/mounts}"
NNET_MOUNT_CMD="${NNET_MOUNT_CMD:-mount}"

nnet_log() {
	echo "nebulaos-network: $*"
	command -v logger >/dev/null 2>&1 && logger -t nebulaos-network -- "$*" 2>/dev/null
	return 0
}

# RFC 1123 single label, lower case, not all digits.
nnet_valid_hostname() {
	case "$1" in
		''|-*|*-|*[!a-z0-9-]*) return 1 ;;
	esac
	[ "${#1}" -le 63 ] || return 1
	case "$1" in
		*[a-z]*) return 0 ;;
	esac
	return 1
}

# Dotted quad, each octet 0-255, no leading zeros.
nnet_valid_ipv4() {
	case "$1" in
		*[!0-9.]*|.*|*.|*..*) return 1 ;;
	esac
	_nnet_ifs=$IFS; IFS=.
	# shellcheck disable=SC2086
	set -- $1
	IFS=$_nnet_ifs
	[ "$#" -eq 4 ] || return 1
	for _o in "$@"; do
		case "$_o" in
			0) ;;
			0*) return 1 ;;
		esac
		[ "${#_o}" -le 3 ] && [ "$_o" -le 255 ] || return 1
	done
	return 0
}

# Reads $NNET_ENV into NNET_* (only the known keys, only through validation).
# Returns 0 with a usable configuration; otherwise leaves the DHCP default and
# returns 1 with the reason in NNET_REASON.
nnet_load() {
	NNET_HOSTNAME="$NNET_DEFAULT_HOSTNAME"
	NNET_MODE=dhcp
	NNET_ADDRESS=""; NNET_NETMASK=""; NNET_GATEWAY=""; NNET_DNS=""
	NNET_REASON=""
	if [ ! -f "$NNET_ENV" ]; then
		NNET_REASON="no_config"
		return 1
	fi
	_h=""; _m=""; _a=""; _n=""; _g=""; _d=""
	while IFS='=' read -r _k _v; do
		_v=${_v#\"}; _v=${_v%\"}
		case "$_k" in
			NNET_HOSTNAME) _h=$_v ;;
			NNET_MODE) _m=$_v ;;
			NNET_ADDRESS) _a=$_v ;;
			NNET_NETMASK) _n=$_v ;;
			NNET_GATEWAY) _g=$_v ;;
			NNET_DNS) _d=$_v ;;
		esac
	done < "$NNET_ENV"
	if ! nnet_valid_hostname "$_h"; then
		NNET_REASON="invalid_hostname"
		return 1
	fi
	case "$_m" in
		dhcp)
			NNET_HOSTNAME=$_h
			return 0 ;;
		static) ;;
		*) NNET_REASON="invalid_mode"; return 1 ;;
	esac
	for _x in "$_a" "$_n" "$_g"; do
		nnet_valid_ipv4 "$_x" || { NNET_REASON="invalid_static_address"; return 1; }
	done
	_dns=""
	_cnt=0
	for _x in $_d; do
		nnet_valid_ipv4 "$_x" || { NNET_REASON="invalid_dns"; return 1; }
		_cnt=$((_cnt + 1))
		[ "$_cnt" -le 3 ] || { NNET_REASON="too_many_dns"; return 1; }
		_dns="${_dns:+$_dns }$_x"
	done
	NNET_HOSTNAME=$_h
	NNET_MODE=static
	NNET_ADDRESS=$_a; NNET_NETMASK=$_n; NNET_GATEWAY=$_g; NNET_DNS=$_dns
	return 0
}

# nnet_render MODE: writes $NNET_IFACES for the current NNET_* values (MODE
# overrides NNET_MODE, so a fallback can render DHCP without reloading).
nnet_render() {
	_mode="${1:-$NNET_MODE}"
	mkdir -p "$NNET_RUN_DIR" 2>/dev/null || return 1
	_tmp="$NNET_IFACES.tmp.$$"
	{
		echo "# generated by /etc/nebulaos-network.sh from $NNET_ENV - do not edit"
		echo "auto lo"
		echo "iface lo inet loopback"
		echo ""
		echo "auto $NNET_IFACE"
		if [ "$_mode" = static ]; then
			echo "iface $NNET_IFACE inet static"
			echo "  address $NNET_ADDRESS"
			echo "  netmask $NNET_NETMASK"
			echo "  gateway $NNET_GATEWAY"
		else
			echo "iface $NNET_IFACE inet dhcp"
			echo "  hostname $NNET_HOSTNAME"
			echo "  wait-delay 15"
			# G23 (2026-10-12): lease events into the (persistent) system log.
			echo "  udhcpc_opts -S"
		fi
	} > "$_tmp" 2>/dev/null || { rm -f "$_tmp"; return 1; }
	mv -f "$_tmp" "$NNET_IFACES" 2>/dev/null || { rm -f "$_tmp"; return 1; }
	return 0
}

# Static mode has no udhcpc to write resolv.conf.
nnet_write_resolv() {
	_tmp="$NNET_RESOLV.tmp.$$"
	{
		for _x in $NNET_DNS; do
			echo "nameserver $_x # $NNET_IFACE"
		done
	} > "$_tmp" 2>/dev/null && cat "$_tmp" > "$NNET_RESOLV" 2>/dev/null
	rm -f "$_tmp"
}

# Rewrites $NNET_HOSTS in place (same inode, so an existing bind mount shows
# the change). Never fails its caller.
nnet_write_hosts() {
	mkdir -p "$NNET_RUN_DIR" 2>/dev/null
	{ printf '127.0.0.1\tlocalhost\n127.0.1.1\t%s\n' "$NNET_HOSTNAME" > "$NNET_HOSTS"; } 2>/dev/null \
		|| nnet_log "could not write $NNET_HOSTS"
	return 0
}

# Binds $NNET_HOSTS over /etc/hosts once per boot. Never fails its caller: the
# image's own /etc/hosts stays if anything is off.
nnet_bind_hosts() {
	[ -f "$NNET_HOSTS" ] || return 0
	grep -q " $NNET_ETC_HOSTS " "$NNET_MOUNTS" 2>/dev/null && return 0
	"$NNET_MOUNT_CMD" --bind "$NNET_HOSTS" "$NNET_ETC_HOSTS" 2>/dev/null \
		|| nnet_log "could not bind $NNET_HOSTS over $NNET_ETC_HOSTS"
	return 0
}

nnet_set_state() {
	mkdir -p "$NNET_RUN_DIR" 2>/dev/null
	{ printf '%s\n' "$1" > "$NNET_STATE"; } 2>/dev/null
}

# Boot entry point, before wpa_supplicant: hostname + interfaces file.
# Returns 0 when $NNET_IFACES is ready for `ifup -i`, 1 when S01wifi must use
# the stock /etc/network/interfaces.
nnet_boot_prepare() {
	if nnet_load; then
		nnet_log "config: hostname=$NNET_HOSTNAME mode=$NNET_MODE"
	else
		nnet_log "config: $NNET_REASON - DHCP, hostname $NNET_HOSTNAME"
	fi
	"$NNET_HOSTNAME_CMD" "$NNET_HOSTNAME" 2>/dev/null \
		|| nnet_log "could not set hostname $NNET_HOSTNAME"
	nnet_write_hosts
	nnet_bind_hosts
	if ! nnet_render; then
		nnet_log "could not write $NNET_IFACES - using /etc/network/interfaces"
		nnet_set_state "DHCP_STOCK_INTERFACES"
		return 1
	fi
	if [ "$NNET_MODE" = static ]; then
		nnet_write_resolv
		nnet_set_state "STATIC_PENDING"
	else
		nnet_set_state "DHCP"
	fi
	return 0
}

# Static mode only, after ifup: prove the gateway answers, otherwise fall back
# to DHCP for this boot (the persisted choice is kept - the printer may simply
# be on another network today). Bounded; S01wifi runs it in the background.
NNET_PROBE_SECONDS="${NNET_PROBE_SECONDS:-20}"
NNET_ARPING="${NNET_ARPING:-arping}"
NNET_IFUP="${NNET_IFUP:-/sbin/ifup}"
NNET_IFDOWN="${NNET_IFDOWN:-/sbin/ifdown}"

nnet_gateway_answers() {
	"$NNET_ARPING" -q -c 1 -w 1 -I "$NNET_IFACE" "$NNET_GATEWAY" >/dev/null 2>&1
}

nnet_static_probe() {
	[ "$NNET_MODE" = static ] || return 0
	_i=0
	while [ "$_i" -lt "$NNET_PROBE_SECONDS" ]; do
		if nnet_gateway_answers; then
			nnet_set_state "STATIC"
			nnet_log "static: gateway $NNET_GATEWAY answers"
			return 0
		fi
		_i=$((_i + 1))
	done
	nnet_log "static: gateway $NNET_GATEWAY silent for ${NNET_PROBE_SECONDS}s - DHCP for this boot"
	"$NNET_IFDOWN" -i "$NNET_IFACES" "$NNET_IFACE" >/dev/null 2>&1
	nnet_render dhcp || return 1
	"$NNET_IFUP" -i "$NNET_IFACES" "$NNET_IFACE" >/dev/null 2>&1
	nnet_set_state "STATIC_FALLBACK_DHCP"
	return 1
}

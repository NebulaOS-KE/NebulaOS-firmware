#!/usr/bin/env python3
"""Generate [adc_temperature nebulaos_ke_bed] for machine.cfg (1.0.5).

Stock Creality KE firmware reads the heated bed with the EPCOS 100K
B57560G104F thermistor and then applies a KE-only correction in its patched
klippy/extras/adc_temperature.py (temp_offset_flag = True on [heater_bed];
stock 1.1.0.17 rootfs, /usr/share/klipper). Upstream Klipper has no such
option, so NebulaOS reproduces the same conversion with a native
[adc_temperature] resistance table: for each raw EPCOS temperature t the
table holds (creality(t), R_epcos(t)).

  creality()  - Creality's algorithm, verbatim (vpt = 40, 52, 84.4, 118.4)
  R_epcos()   - upstream Klipper's own EPCOS curve: the Steinhart-Hart fit of
                [thermistor EPCOS 100K B57560G104F] in temperature_sensors.cfg
                (25 C/100000, 150 C/1641.9, 250 C/226.15), 4700 ohm pullup

Usage: ke-bed-temperature-table.py   (prints the section)
"""
import math

STEP = 1.0            # raw EPCOS temperature step (C)
LOW, HIGH = -5.0, 135.0
BREAKPOINTS = (40.0, 52.0, 84.4, 118.4)   # Creality's vpt: exact corners
SECTION = "adc_temperature nebulaos_ke_bed"

# Steinhart-Hart coefficients exactly as Klipper's Thermistor.setup_coefficients
def _sh(t1, r1, t2, r2, t3, r3):
    inv_t1, inv_t2, inv_t3 = (1. / (t - (-273.15)) for t in (t1, t2, t3))
    ln_r1, ln_r2, ln_r3 = math.log(r1), math.log(r2), math.log(r3)
    ln3_r1, ln3_r2, ln3_r3 = ln_r1 ** 3, ln_r2 ** 3, ln_r3 ** 3
    inv_t12, inv_t13 = inv_t1 - inv_t2, inv_t1 - inv_t3
    ln_r12, ln_r13 = ln_r1 - ln_r2, ln_r1 - ln_r3
    ln3_r12, ln3_r13 = ln3_r1 - ln3_r2, ln3_r1 - ln3_r3
    c3 = ((inv_t12 - inv_t13 * ln_r12 / ln_r13)
          / (ln3_r12 - ln3_r13 * ln_r12 / ln_r13))
    c2 = (inv_t12 - c3 * ln3_r12) / ln_r12
    c1 = inv_t1 - c2 * ln_r1 - c3 * ln3_r1
    return c1, c2, c3

C1, C2, C3 = _sh(25., 100000., 150., 1641.9, 250., 226.15)


def r_epcos(t):
    """Resistance (ohm) of the EPCOS curve at temperature t, as Klipper's
    Thermistor.calc_adc computes it (no inline resistor)."""
    inv_t = 1. / (t - (-273.15))
    if C3:
        y = (C1 - inv_t) / (2. * C3)
        x = math.sqrt((C2 / (3. * C3)) ** 3 + y ** 2)
        ln_r = math.pow(x - y, 1. / 3.) - math.pow(x + y, 1. / 3.)
    else:
        ln_r = (inv_t - C1) / C2
    return math.exp(ln_r)


def t_epcos(r):
    """Temperature of the EPCOS curve at resistance r (Klipper calc_temp)."""
    ln_r = math.log(r)
    inv_t = C1 + C2 * ln_r + C3 * ln_r ** 3
    return 1. / inv_t + (-273.15)


def creality(t1):
    """Creality KE adc_temperature.py adc_callback, temp_offset_flag True."""
    vpt = [40, 52, 84.4, 118.4]
    if (t1 > vpt[0]) & (t1 < vpt[1]):
        temp = (t1 - vpt[0]) * (10 / (vpt[1] - vpt[0])) + vpt[0]
    elif (t1 >= vpt[1]) & (t1 < vpt[2]):
        temp = (t1 - vpt[1]) * (30 / (vpt[2] - vpt[1])) + 50
    elif t1 >= vpt[2]:
        temp = (t1 - vpt[2]) * (30 / (vpt[3] - vpt[2])) + 80
    else:
        temp = t1
    return temp


def raw_points():
    pts, n = set(), 0
    while LOW + n * STEP <= HIGH + 1e-9:
        pts.add(round(LOW + n * STEP, 4))
        n += 1
    return sorted(pts | set(BREAKPOINTS))


def samples():
    """[(corrected temperature, resistance)], rounded as written."""
    return [(round(creality(t), 4), round(r_epcos(t), 3)) for t in raw_points()]


def section_text():
    out = ["[%s]" % SECTION,
           "# GENERATED by tools/klipper-config/ke-bed-temperature-table.py - do not edit.",
           "# Creality KE bed correction (temp_offset_flag) over the EPCOS 100K",
           "# B57560G104F curve; tests/ke-bed-temperature-tests.py checks it."]
    for i, (t, r) in enumerate(samples(), 1):
        out.append("temperature%d: %s" % (i, ("%.4f" % t).rstrip("0").rstrip(".")))
        out.append("resistance%d: %s" % (i, ("%.3f" % r).rstrip("0").rstrip(".")))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    import sys
    sys.stdout.write(section_text())
